async def seed():
    """Seed all learning content into the database."""
    async with AsyncSessionLocal() as db:
        # Ensure a default user exists
        from sqlalchemy import select as sel
        result = await db.execute(sel(User).where(User.id == 1))
        user = result.scalar_one_or_none()
        if not user:
            user = User(id=1, username="default", email="default@investlearn.local")
            db.add(user)
            await db.flush()

        # Seed categories
        cat_map = {}
        for c in CATEGORIES:
            result = await db.execute(sel(LearnCategory).where(LearnCategory.slug == c["slug"]))
            existing = result.scalar_one_or_none()
            if existing:
                cat_map[c["slug"]] = existing.id
            else:
                cat = LearnCategory(**c)
                db.add(cat)
                await db.flush()
                cat_map[c["slug"]] = cat.id
        print(f"Seeded {len(cat_map)} categories")

        # Seed articles
        article_count = 0
        for a in ARTICLES:
            result = await db.execute(sel(LearnArticle).where(LearnArticle.slug == a["slug"]))
            if result.scalar_one_or_none():
                continue
            article = LearnArticle(
                category_id=cat_map.get(a["category"]),
                title=a["title"], slug=a["slug"], summary=a["summary"],
                content=a["content"], level=a["level"],
                estimated_read=a["estimated_read"], tags=a["tags"],
                is_published=True, published_at=datetime.now(timezone.utc),
            )
            db.add(article)
            article_count += 1
        print(f"Seeded {article_count} articles")

        # Seed glossary
        glossary_count = 0
        for g in GLOSSARY:
            result = await db.execute(sel(GlossaryTerm).where(GlossaryTerm.term == g["term"]))
            if result.scalar_one_or_none():
                continue
            db.add(GlossaryTerm(**g))
            glossary_count += 1
        print(f"Seeded {glossary_count} glossary terms")

        # Seed strategies
        strategy_count = 0
        for s in STRATEGIES:
            result = await db.execute(sel(InvestmentStrategy).where(InvestmentStrategy.slug == s["slug"]))
            if result.scalar_one_or_none():
                continue
            db.add(InvestmentStrategy(**s))
            strategy_count += 1
        print(f"Seeded {strategy_count} strategies")

        # News: real RSS feeds synced by scheduler (crawl_news job every 15 min)
        # Initialize RSS sources if not present
        from app.crawlers.news import NEWS_SOURCES
        src_count = 0
        for s in NEWS_SOURCES:
            exist = await db.execute(sel(NewsSource).where(NewsSource.name == s["name"]))
            if not exist.scalar_one_or_none():
                db.add(NewsSource(**s))
                src_count += 1
        if src_count:
            print(f"Initialized {src_count} RSS news sources")
        else:
            print("RSS news sources already exist")

        await db.commit()
        print("✅ Seed completed successfully!")


if __name__ == "__main__":
    asyncio.run(seed())
